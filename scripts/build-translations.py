#!/usr/bin/env python3
"""Build browser dictionaries from the reviewed local translation catalogue.
Run: node scripts/home-fragments.cjs && python3 scripts/collect-translations.py
     python3 scripts/build-translations.py
Collection requires BeautifulSoup 4; building only requires Python's standard library.
"""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
manifest=json.loads(Path('/tmp/translation-manifest.json').read_text())
catalog=json.loads((ROOT/'assets/i18n/catalog.json').read_text())
known_pages=sorted([*manifest, 'AIalbum.html'])
for name, strings in manifest.items():
    missing=[(lang,s) for s in strings for lang in ['ja','es'] if s not in catalog[lang] or not catalog[lang][s].strip()]
    if missing: raise ValueError(f'Missing translations in {name}: {missing}')
    data={'defaultLanguage':'ja' if name=='ketsuatsu_shindan.html' else 'en', 'pages':known_pages,
          'strings':{s:[s,catalog['ja'][s],catalog['es'][s]] for s in strings}}
    # This page was authored in Japanese; supply English for its English option.
    if name=='ketsuatsu_shindan.html':
        for s in strings: data['strings'][s][0]=catalog['en'].get(s,s)
    path=ROOT/'assets/i18n'/name.replace('/','__').replace('.html','.js')
    path.write_text('// Generated by scripts/build-translations.py; edit catalog.json instead.\nwindow.SiteTranslations = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n')
print(f'Built {len(manifest)} page dictionaries ({len(known_pages)} pages including the existing album).')
